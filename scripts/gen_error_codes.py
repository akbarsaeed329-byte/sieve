"""Regenerate docs/ERROR_CODES.md from sieve/errors.py (a test keeps them in sync)."""
from pathlib import Path

import sieve.errors as e

EXTRA = {"SIEVE-INV-422": "The model asked for an unknown or incomplete query template; it is refused and the loop stops.",
         "SIEVE-PLG-428": "Approve the plugin's permissions to enable it.",
         "SIEVE-PLG-500": "A plugin crashed; it was contained. Check the logs.",
         "SIEVE-PLG-504": "A plugin timed out; the incident is marked partial context.",
         "SIEVE-LLM-404": "The Ollama model is not pulled; run the command shown.",
         "SIEVE-NET-000": "The browser cannot reach Sieve; check that it is running."}
codes = sorted({v for k, v in vars(e).items() if k.isupper() and isinstance(v, str) and v.startswith("SIEVE-")})
lines = ["# Error codes", "", "Every user-facing error has a stable code, a message and a fix. Generated by",
         "`python scripts/gen_error_codes.py` from `sieve/errors.py`; a test keeps this file in sync.", "",
         "| Code | Usual fix |", "| --- | --- |"]
lines += [f"| {c} | {e.FIXES.get(c, '')} |" for c in codes] + [f"| {c} | {f} |" for c, f in EXTRA.items()]
Path(__file__).resolve().parents[1].joinpath("docs/ERROR_CODES.md").write_text("\n".join(lines) + "\n")
print(len(codes) + len(EXTRA), "codes")
